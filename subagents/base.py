# =============================================================================
#  Codermuks in Termux — базовый субагент
# =============================================================================
#  Все субагенты (coder, tester, researcher, file_manager) наследуются от
#  этого класса. Он задаёт общий интерфейс и переиспользуемые утилиты.
#
#  Что даёт базовый класс:
#    • единый метод run(task) — точка входа для менеджера;
#    • удобные обёртки над клиентом Mistral;
#    • хелпер для извлечения блоков кода из ответа модели;
#    • систему логирования шагов субагента.
# =============================================================================

from __future__ import annotations

import re
from typing import Any

from core.mistral_client import MistralClient, get_client


# =============================================================================
#  РЕГУЛЯРНОЕ ВЫРАЖЕНИЕ ДЛЯ БЛОКОВ КОДА
# =============================================================================

# Ищет блоки вида:
#   ```python
#   print("hello")
#   ```
# Группа 1 — необязательное имя языка, группа 2 — сам код.
CODE_BLOCK_RE = re.compile(
    r"```([a-zA-Z0-9_+\-#]*)\s*\n(.*?)```",
    re.DOTALL,
)


# =============================================================================
#  БАЗОВЫЙ КЛАСС
# =============================================================================

class BaseSubagent:
    """
    Базовый субагент.

    Каждый конкретный субагент переопределяет метод `run(task, **kwargs)`
    и, при необходимости, добавляет свои вспомогательные методы.
    """

    # Имя субагента. Переопределяется в наследниках.
    name: str = "base"

    # Краткое описание — используется в логах и справке.
    description: str = "Базовый субагент."

    def __init__(self) -> None:
        # Ленивая ссылка на клиент Mistral — читаем ключ при первом запросе.
        self._client: MistralClient | None = None
        # Лог шагов — полезно для отладки.
        self._log: list[str] = []

    # -------------------------------------------------------------------------
    #  Клиент Mistral
    # -------------------------------------------------------------------------

    @property
    def client(self) -> MistralClient:
        """
        Возвращает клиент Mistral.

        Создаётся лениво, чтобы импорт модуля не требовал ключа.
        """
        if self._client is None:
            self._client = get_client()
        return self._client

    # -------------------------------------------------------------------------
    #  Логирование
    # -------------------------------------------------------------------------

    def log(self, message: str) -> None:
        """Добавляет сообщение в лог субагента."""
        self._log.append(f"[{self.name}] {message}")

    def get_log(self) -> list[str]:
        """Возвращает накопленный лог."""
        return list(self._log)

    def clear_log(self) -> None:
        """Очищает лог."""
        self._log.clear()

    # -------------------------------------------------------------------------
    #  Работа с блоками кода
    # -------------------------------------------------------------------------

    def extract_code_blocks(self, text: str) -> list[tuple[str, str]]:
        """
        Извлекает все блоки кода из текста ответа модели.

        Возвращает список кортежей (язык, код). Если язык не указан —
        пустая строка.

        Пример:
            >>> extract_code_blocks("```python\\nprint('x')\\n```")
            [("python", "print('x')")]
        """
        blocks: list[tuple[str, str]] = []
        for match in CODE_BLOCK_RE.finditer(text):
            lang = (match.group(1) or "").strip().lower()
            code = match.group(2).rstrip()
            if code:
                blocks.append((lang, code))
        return blocks

    def extract_first_code(self, text: str) -> tuple[str, str]:
        """
        Возвращает первый блок кода из текста.

        Если блоков нет — возвращает ("", "").
        """
        blocks = self.extract_code_blocks(text)
        if not blocks:
            return "", ""
        return blocks[0]

    # -------------------------------------------------------------------------
    #  Интерфейс для наследников
    # -------------------------------------------------------------------------

    def run(self, task: str, **kwargs: Any) -> str:
        """
        Выполняет задачу.

        Наследники обязаны переопределить этот метод.

        Аргументы:
            task    — текстовая задача
            **kwargs — дополнительные параметры

        Возвращает:
            Строку с результатом работы.
        """
        raise NotImplementedError(
            f"Субагент '{self.name}' не реализует метод run()."
        )