# =============================================================================
#  Этот пакет отвечает за перевод интерфейса на разные языки.
#
#  Как это работает:
#    1. main.py определяет язык пользователя (из config.json).
#    2. Вызывает translator.init("ru") или translator.init("en").
#    3. Дальше все модули получают перевод через функцию t("ключ").
#
#  Структура пакета:
#    • translator.py — менеджер переводов (функции t, init, get_language);
#    • en.py         — английские строки (словарь STRINGS);
#    • ru.py         — русские строки (словарь STRINGS).
#
#  Пример использования:
#      from core.i18n import t
#      print(t("welcome.banner"))   # → "CODERMUKS in TERMUX"
#      print(t("cmd.exit"))          # → "выйти из программы" (если язык ru)
#
#  Если ключ не найден — возвращается сам ключ, чтобы не падать.
#  Это удобно при разработке: сразу видно, какой перевод забыли.
# =============================================================================

