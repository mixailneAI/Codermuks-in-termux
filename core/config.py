def ensure_dirs() -> None:
    """
    Создаёт все необходимые директории, если их ещё нет.

    Вызывается один раз при старте приложения, чтобы остальной код
    мог не беспокоиться о существовании путей.
    """
    USER_DIR.mkdir(parents=True, exist_ok=True)
    ARTIFACTS_DIR.mkdir(parents=True, exist_ok=True)
    TEMP_DIR.mkdir(parents=True, exist_ok=True)


def get_api_key() -> str:
    """
    Читает API-ключ Mistral из файла ~/.codermuks/key.txt.

    Возвращает:
        Строку с ключом (без пробелов по краям).

    Исключения:
        FileNotFoundError — если файл ключа отсутствует.
        ValueError        — если ключ пустой или это заглушка.
    """
    if not KEY_FILE.exists():
        raise FileNotFoundError(
            f"Файл с ключом не найден: {KEY_FILE}\n"
            f"Вставь ключ: nano {KEY_FILE}\n"
            f"Получить бесплатный ключ: https://console.mistral.ai/api-keys"
        )

    # Читаем файл и берём первую непустую строку, которая не начинается с '#'.
    # Это позволяет хранить в файле комментарии и заголовки.
    raw_lines = KEY_FILE.read_text(encoding="utf-8").splitlines()
    key = ""
    for line in raw_lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        key = stripped
        break

    if not key:
        raise ValueError(
            f"Файл с ключом пуст: {KEY_FILE}\n"
            f"Вставь свой API-ключ Mistral и повтори запуск."
        )

    if key == "ВСТАВЬ_СЮДА_СВОЙ_MISTRAL_API_KEY":
        raise ValueError(
            f"API-ключ ещё не вставлен.\n"
            f"Открой файл и замени заглушку на свой ключ: nano {KEY_FILE}\n"
            f"Получить бесплатный ключ: https://console.mistral.ai/api-keys"
        )

    return key


def get_base_url() -> str:
    """
    Возвращает базовый URL Mistral API.

    Вынесено в отдельную функцию, чтобы в будущем можно было легко
    переключиться на прокси или другую совместимую точку входа.
    """
    return os.environ.get("MISTRAL_BASE_URL", "https://api.mistral.ai/v1")


def is_termux() -> bool:
    """
    Проверяет, запущено ли приложение в Termux.

    Termux всегда определяет переменную окружения PREFIX и кладёт
    свои бинарники в /data/data/com.termux/files/usr.
    """
    prefix = os.environ.get("PREFIX", "")
    return "com.termux" in prefix or Path("/data/data/com.termux").exists()


def get_python_executable() -> str:
    """
    Возвращает путь к текущему интерпретатору Python.

    Используется раннером для запуска Python-скриптов в изолированном
    подпроцессе — чтобы гарантированно был тот же интерпретатор,
    что и у самого Codermuks.
    """
    return sys.executable


