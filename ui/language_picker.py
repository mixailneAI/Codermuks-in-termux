# =============================================================================
#  Codermuks in Termux — меню выбора языка интерфейса v1.1.0
# =============================================================================
#  Что делает этот модуль:
#    • показывает мини-окно выбора языка при первом запуске;
#    • варианты: English / Русский;
#    • возвращает код языка ("en" или "ru");
#    • если пользователь прервал ввод — возвращает None.
#
#  ВАЖНО: этот модуль работает БЕЗ переводов и без rich.
#  Причина: язык ещё не выбран, и мы не знаем, на каком языке
#  выводить сообщения. Поэтому рамка рисуется напрямую через print(),
#  а названия языков показываются одновременно на обоих языках.
# =============================================================================

from __future__ import annotations


# =============================================================================
#  КОНСТАНТЫ РАМКИ
# =============================================================================

# Внутренняя ширина меню (между рамками).
_INNER_WIDTH: int = 53

# Символы для верхней, средней и нижней границы.
_BORDER_TOP    = "╔" + "═" * (_INNER_WIDTH + 2) + "╗"
_BORDER_MID    = "║" + " " * (_INNER_WIDTH + 2) + "║"
_BORDER_BOTTOM = "╚" + "═" * (_INNER_WIDTH + 2) + "╝"


# =============================================================================
#  УТИЛИТЫ
# =============================================================================

def _center(text: str) -> str:
    """
    Центрует текст внутри рамки.

    Если текст длиннее внутренней ширины — обрезает.
    """
    if len(text) >= _INNER_WIDTH:
        return text[:_INNER_WIDTH]

    left = (_INNER_WIDTH - len(text)) // 2
    right = _INNER_WIDTH - len(text) - left
    return " " * left + text + " " * right


def _row(text: str = "") -> str:
    """Возвращает строку внутри рамки с центрированным текстом."""
    return "║ " + _center(text) + " ║"


# =============================================================================
#  ОТРИСОВКА МЕНЮ
# =============================================================================

def _print_menu() -> None:
    """
    Печатает меню выбора языка.

    Тексты дублируются на двух языках, потому что пользователь ещё
    не выбрал, какой использовать. Это единственное место в проекте,
    где интерфейс двуязычен одновременно.
    """
    print()
    print(_BORDER_TOP)
    print(_BORDER_MID)
    print(_row("Select a language · Выберите язык"))
    print(_BORDER_MID)
    print(_row("[1] English"))
    print(_row("[2] Русский"))
    print(_BORDER_MID)
    print(_BORDER_BOTTOM)
    print()


# =============================================================================
#  ОСНОВНАЯ ФУНКЦИЯ
# =============================================================================

def pick_language(max_attempts: int = 5) -> str | None:
    """
    Спрашивает пользователя, какой язык интерфейса использовать.

    Аргументы:
        max_attempts — сколько раз позволить ошибиться с вводом.
                       По умолчанию 5. После этого возвращает None.

    Возвращает:
        "en"  — если выбран английский.
        "ru"  — если выбран русский.
        None  — если пользователь прервал ввод (Ctrl+C / Ctrl+D)
                или исчерпал попытки.

    Пример:
        lang = pick_language()
        if lang is None:
            print("Language not selected. Exiting.")
            return 1
    """
    _print_menu()

    prompt = "Enter number · Введите номер: "

    for _ in range(max_attempts):
        try:
            answer = input(prompt).strip()
        except (KeyboardInterrupt, EOFError):
            # Пользователь нажал Ctrl+C или Ctrl+D — выходим без выбора.
            print()
            return None

        if not answer:
            continue

        # Принимаем и цифры, и явные названия языков.
        low = answer.lower()

        if low in ("1", "en", "eng", "english", "англ", "английский"):
            return "en"

        if low in ("2", "ru", "rus", "russian", "рус", "русский"):
            return "ru"

        # Неверный ввод — показываем подсказку и повторяем.
        print("  Invalid · Неверно. Enter 1 or 2 · Введи 1 или 2.")
        print()

    # Исчерпали попытки.
    return None


# =============================================================================
#  ЭКСПОРТ
# =============================================================================

__all__ = ["pick_language"]