#!/usr/bin/env python3
# =============================================================================
#  Codermuks in Termux — точка входа v1.1.0
# =============================================================================
#  Порядок работы main.py:
#    1. Добавляет корень проекта в sys.path, чтобы работали импорты
#       вида `from core.config import ...`.
#    2. Проверяет, выбран ли язык интерфейса (поле language в config.json).
#       Если нет — показывает меню выбора языка (EN/RU).
#    3. Загружает переводчик с выбранным языком.
#    4. Передаёт управление в ui/cli.py.
#
#  Запускается либо напрямую (`python main.py`), либо через лаунчер
#  `codermuks`, который лежит рядом и делает то же самое.
# =============================================================================

import sys
import os
import traceback


# --- Корень проекта в sys.path ---------------------------------------------
PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))
if PROJECT_DIR not in sys.path:
    sys.path.insert(0, PROJECT_DIR)


# --- Импорт модулей проекта ------------------------------------------------
# Импортируем после правки sys.path, иначе Python не найдёт core/ui/etc.

from core import config
from core.i18n import translator
from ui.language_picker import pick_language
from ui.cli import run


# --- Главная функция -------------------------------------------------------
def main() -> int:
    """
    Точка входа Codermuks.

    Возвращает код выхода:
        0   — успешное завершение
        1   — ошибка (нет ключей, сломан config.json и т. п.)
        130 — прервано пользователем (Ctrl+C)
    """
    try:
        # --- Шаг 1: создаём пользовательские директории --------------------
        # На случай, если config.json или key.txt удалили вручную.
        config.ensure_dirs()

        # --- Шаг 2: определяем язык интерфейса -----------------------------
        language = config.get_language()

        if language is None:
            # Язык ещё не выбран — показываем меню выбора.
            # Меню рисуется простыми ASCII-рамками, потому что мы ещё
            # не знаем языка и не можем использовать rich-переводы.
            language = pick_language()

            if language is None:
                # Пользователь прервал выбор (Ctrl+C или ввёл не то много раз).
                print("Language not selected. Exiting.")
                print("Язык не выбран. Выход.")
                return 1

            # Сохраняем выбор в config.json, чтобы больше не спрашивать.
            config.set_language(language)

        # --- Шаг 3: инициализируем переводчик ------------------------------
        translator.init(language)

        # --- Шаг 4: передаём управление CLI --------------------------------
        return run()

    except KeyboardInterrupt:
        # Пользователь нажал Ctrl+C — выходим вежливо.
        print("\n[!] Прервано пользователем.")
        return 130

    except Exception as exc:
        # Любая непредвиденная ошибка — показываем и выходим.
        print(f"[✘] Непредвиденная ошибка: {exc}")
        print("[i] Подробности:")
        traceback.print_exc()
        return 1


# --- Точка входа -----------------------------------------------------------
if __name__ == "__main__":
    sys.exit(main())