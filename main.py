#!/usr/bin/env python3
# =============================================================================
#  Codermuks in Termux — точка входа
# =============================================================================
#  Этот файл — минимальная обёртка. Вся логика находится в модулях:
#    • ui/cli.py         — интерфейс терминала (баннер, промпт, вывод)
#    • core/agent.py     — оркестратор, который решает задачу
#    • core/config.py    — конфигурация, чтение ключа Mistral
#
#  Запускается либо напрямую (`python main.py`), либо через лаунчер
#  `codermuks`, который лежит рядом и делает то же самое.
# =============================================================================

import sys
import os

# --- Добавляем директорию проекта в sys.path -------------------------------
# Это нужно, чтобы импорты вида `from core.config import ...` работали
# независимо от того, из какой директории пользователь запустил программу.
PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))
if PROJECT_DIR not in sys.path:
    sys.path.insert(0, PROJECT_DIR)

# --- Импортируем точку входа CLI -------------------------------------------
from ui.cli import run


# --- Главная функция --------------------------------------------------------
def main() -> int:
    """
    Запускает CLI Codermuks in Termux.

    Возвращает код выхода:
        0 — успешное завершение
        1 — ошибка (например, отсутствует ключ Mistral)
        130 — прервано пользователем (Ctrl+C)
    """
    try:
        return run()
    except KeyboardInterrupt:
        # Пользователь нажал Ctrl+C — выходим вежливо.
        print("\n\033[33m[!]\033[0m Прервано пользователем.")
        return 130
    except Exception as exc:
        # Любая непредвиденная ошибка — показываем и выходим.
        print(f"\033[31m[✘]\033[0m Непредвиденная ошибка: {exc}")
        return 1


# --- Точка входа ------------------------------------------------------------
if __name__ == "__main__":
    sys.exit(main())